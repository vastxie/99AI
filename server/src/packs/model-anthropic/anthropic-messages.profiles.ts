/**
 * 目录条目按能力表写推理档位（只在后台新选择目录条目时写进表单，已保存的模型保持自己的配置）：
 * adaptive 家族列出支持的档位、默认「中」；手动思考家族默认「关闭」；不支持思考的不写
 */
const ANTHROPIC_MODEL_CATALOG: ModelGatewayCatalogItem[] = ANTHROPIC_MODEL_CATALOG_BASE.map(
  item => {
    const reasoningControl = anthropicCatalogReasoningControl(item.id);
    return reasoningControl
      ? { ...item, capabilities: { ...item.capabilities, reasoningControl } }
      : item;
  },
);

